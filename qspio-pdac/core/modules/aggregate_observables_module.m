% Aggregate Observables Module
%
% Defines derived non-species quantities that aggregate over multiple model
% species. These centralize denominators / totals that calibration target
% observable code would otherwise re-encode per target — a brittle pattern
% that drifts when species are added or renamed.
%
% Every sum a calibration readout needs is defined here, and the readout names
% the aggregate rather than listing its members. A pool added to a lineage then
% reaches the readouts through this file alone, instead of each target carrying
% a copy of the membership that goes stale without saying so.
%
% Inputs: model -- SimBiology model object with four compartments
% Outputs: model -- SimBiology model object with aggregate observables
%
% Dependencies (must run last in module assembly, after all species exist):
%   cancer_module      -- V_T.C1, V_T.C_x
%   Treg_module        -- V_T.Treg
%   Teff_module        -- V_T.CD8, V_T.CD8_exh
%   Th_module          -- V_T.Th, V_T.Th_exh
%   APC_module         -- V_T.cDC1, V_T.cDC2, V_T.mcDC1, V_T.mcDC2
%   MDSC_module        -- V_T.MDSC
%   macrophage_module  -- V_T.Mac_M1, V_T.Mac_M2
%   fibroblast_module  -- V_T.qPSC, V_T.iCAF, V_T.myCAF, V_T.apCAF

function model = aggregate_observables_module(model)

% CD8_total_T: all CD8 T cells counted by a (pan-)CD8 IHC/flow assay --
% functional effectors (V_T.CD8) + terminal exhausted (V_T.CD8_exh) + progenitor-
% exhausted (V_T.CD8_pex). Single source of truth for "total CD8": every
% total-CD8 observable references this, so future CD8-subpool changes touch only
% this rule, not each calibration target.
addparameter(model, 'CD8_total_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', ['Total CD8 T cells in V_T (naive + effector + terminal-exhausted + ' ...
              'progenitor-exhausted). Aggregate alias for total-CD8 observables.']);
addrule(model, 'CD8_total_T = V_T.CD8 + V_T.CD8_exh + V_T.CD8_pex + V_T.nCD8', ...
    'repeatedAssignment');

% nucleated_total_T: all nucleated cells in V_T
addparameter(model, 'nucleated_total_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', ['All nucleated cells in V_T (cancer + immune + CAFs). ' ...
              'Used as the denominator for _pct_ calibration targets ' ...
              'matching mIHC "% of all nucleated cells" measurements.']);

addrule(model, ['nucleated_total_T = ' ...
    'V_T.C1 + V_T.C_x' ...
    ' + CD8_total_T' ...
    ' + V_T.nCD4 + V_T.Th + V_T.Th_exh + V_T.Treg' ...
    ' + V_T.Mac_M1 + V_T.Mac_M2' ...
    ' + V_T.MDSC' ...
    ' + V_T.cDC1 + V_T.cDC2 + V_T.mcDC1 + V_T.mcDC2' ...
    ' + V_T.nB + V_T.aB + V_T.Plasma' ...
    ' + V_T.Tfh' ...
    ' + V_T.qPSC + V_T.iCAF + V_T.myCAF + V_T.apCAF'], ...
    'repeatedAssignment');

% --- Lineages the calibration readouts count over -------------------------
% One aggregate per denominator or numerator a target names. Ordering is by
% dependency for readability only; SimBiology sorts repeated assignments itself.

% CD8_exh_total_T: the PD-1+ exhausted CD8 pools -- terminal (CD8_exh) and
% progenitor (CD8_pex, the PD-1+TCF1+ Tpex reservoir). What an exhausted-fraction
% readout reports.
addparameter(model, 'CD8_exh_total_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', 'Exhausted CD8 T cells in V_T (terminal + progenitor-exhausted).');
addrule(model, 'CD8_exh_total_T = V_T.CD8_exh + V_T.CD8_pex', ...
    'repeatedAssignment');

% Th_total_T: conventional CD4 helper cells, excluding Treg.
addparameter(model, 'Th_total_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', 'Conventional CD4 helper T cells in V_T (naive/effector + exhausted), excluding Treg.');
addrule(model, 'Th_total_T = V_T.Th + V_T.Th_exh + V_T.nCD4', 'repeatedAssignment');

% CD4_total_T: everything a CD4 stain counts, Treg included.
addparameter(model, 'CD4_total_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', 'All CD4 T cells in V_T (naive + conventional helper + Treg).');
addrule(model, 'CD4_total_T = Th_total_T + V_T.Treg', 'repeatedAssignment');

% Tcell_total_T: what a CD3 stain counts.
addparameter(model, 'Tcell_total_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', 'All T cells in V_T (CD8 + CD4), the model side of a pan-CD3 stain.');
addrule(model, 'Tcell_total_T = CD8_total_T + CD4_total_T', 'repeatedAssignment');

% Mac_total_T: what a pan-macrophage stain counts.
addparameter(model, 'Mac_total_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', 'Tumour-associated macrophages in V_T (M1-like + M2-like).');
addrule(model, 'Mac_total_T = V_T.Mac_M1 + V_T.Mac_M2', 'repeatedAssignment');

% DC_total_T / mDC_total_T: dendritic cells, and the mature subset a DC-LAMP
% (CD208/LAMP3) stain picks out.
addparameter(model, 'DC_total_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', 'All dendritic cells in V_T (immature + mature, cDC1 + cDC2).');
addrule(model, 'DC_total_T = V_T.cDC1 + V_T.cDC2 + V_T.mcDC1 + V_T.mcDC2', ...
    'repeatedAssignment');

addparameter(model, 'mDC_total_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', 'Mature dendritic cells in V_T (mcDC1 + mcDC2), the DC-LAMP+ subset.');
addrule(model, 'mDC_total_T = V_T.mcDC1 + V_T.mcDC2', 'repeatedAssignment');

% cDC1/cDC2 lineages: a subtype stain does not resolve maturation state, so it
% counts immature and mature of one lineage together.
addparameter(model, 'cDC1_lineage_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', 'cDC1 lineage in V_T at any maturation state (cDC1 + mcDC1).');
addrule(model, 'cDC1_lineage_T = V_T.cDC1 + V_T.mcDC1', 'repeatedAssignment');

addparameter(model, 'cDC2_lineage_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', 'cDC2 lineage in V_T at any maturation state (cDC2 + mcDC2).');
addrule(model, 'cDC2_lineage_T = V_T.cDC2 + V_T.mcDC2', 'repeatedAssignment');

% immune_total_T: all leukocytes in V_T. The denominator when a study reports a
% fraction "of all cells in the ROI" inside a lymphoid aggregate, where cancer
% cells and CAFs are absent by construction.
addparameter(model, 'immune_total_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', ['All leukocytes in V_T (T cells + macrophages + MDSC + DC). ' ...
              'Excludes cancer cells and CAFs, unlike nucleated_total_T.']);
addrule(model, ['immune_total_T = Tcell_total_T' ...
    ' + Mac_total_T + V_T.MDSC + DC_total_T'], 'repeatedAssignment');

% CD8_total_C: whole-repertoire CD8 count in blood, what a flow panel counts.
% V_C.nCD8 is a PER-CLONE species -- Teff_module initializes it as nCD8_C /
% div_CD8 and thymic output enters at Q_nCD8_thym / div_CD8 -- so it is
% multiplied back up by the repertoire diversity here rather than in each
% observable. V_C.CD8 is the single expanded tumour-antigen-specific clone and is
% added unscaled (it contributes <0.1%).
addparameter(model, 'CD8_total_C', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', ['Whole-repertoire CD8 T cells in V_C (per-clone naive pool scaled ' ...
              'by div_CD8, plus the expanded antigen-specific clone).']);
addrule(model, 'CD8_total_C = V_C.nCD8 * div_CD8 + V_C.CD8', 'repeatedAssignment');

% CAF_total_T: activated fibroblasts. Excludes the quiescent V_T.qPSC, which a
% CAF-subtype stain does not count.
addparameter(model, 'CAF_total_T', 0, ...
    'ValueUnits', 'cell', 'ConstantValue', false, ...
    'Notes', ['Activated cancer-associated fibroblasts in V_T ' ...
              '(iCAF + myCAF + apCAF). Excludes quiescent qPSC.']);
addrule(model, 'CAF_total_T = V_T.iCAF + V_T.myCAF + V_T.apCAF', 'repeatedAssignment');

end
