function config = PSA_filter_config()
%PSA_FILTER_CONFIG Configure plausibility filters for PSA
%
% Defines filters to identify physiologically plausible patients.
% These filters are applied to model outputs to exclude patients with
% unrealistic results.

config = struct();
config.filters = struct();

%% Tumor Volume Filters
config.filters.tumor_volume_final = struct(...
    'type', 'compartment', ...
    'name', 'V_T', ...
    'lower_bound', 0, ...
    'upper_bound', 1500, ...
    'units', 'milliliter', ...
    'description', 'Tumor volume at end must be physiologically reasonable', ...
    'timepoint', 'final');

%% T Cell Count Filters
config.filters.Teff_tumor_final = struct(...
    'type', 'species', ...
    'name', 'Teff', ...
    'lower_bound', 0, ...
    'upper_bound', 1e15, ...
    'units', 'cell', ...
    'description', 'CD8+ T effector cells in tumor must be within physiological range', ...
    'timepoint', 'final', ...
    'compartment', 'V_T');

config.filters.Treg_tumor_final = struct(...
    'type', 'species', ...
    'name', 'Treg', ...
    'lower_bound', 0, ...
    'upper_bound', 1e15, ...
    'units', 'cell', ...
    'description', 'Regulatory T cells in tumor must be within physiological range', ...
    'timepoint', 'final', ...
    'compartment', 'V_T');

%% Cell Density Filters
config.filters.CD8_density_final = struct(...
    'type', 'calculated', ...
    'name', 'CD8_density', ...
    'lower_bound', 1e5, ...
    'upper_bound', 1e9, ...
    'units', 'cell/milliliter', ...
    'description', 'CD8+ T cell density in tumor must be physiologically plausible', ...
    'timepoint', 'final');

config.filters.CD4_density_final = struct(...
    'type', 'calculated', ...
    'name', 'CD4_density', ...
    'lower_bound', 1e5, ...
    'upper_bound', 5e9, ...
    'units', 'cell/milliliter', ...
    'description', 'CD4+ T cell density in tumor must be physiologically plausible', ...
    'timepoint', 'final');

end
