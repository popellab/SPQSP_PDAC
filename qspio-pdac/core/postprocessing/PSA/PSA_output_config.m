function config = PSA_output_config()
%PSA_OUTPUT_CONFIG Configure outputs for Parameter Sensitivity Analysis
%
% Defines what model outputs to track for analysis. These outputs can be
% used for sensitivity analysis, biomarker identification, virtual patient
% generation, or any other analysis.
%
% Output Types:
%   'species'    - Model species (e.g., cell counts)
%   'parameter'  - Model parameters
%   'compartment'- Compartment volumes
%   'calculated' - Postprocessed values (ratios, densities, etc.)
%   'baseline'   - Initial values
%   'final'      - End-of-simulation values

config = struct();
config.outputs = struct();

%% T Cell Ratios
config.outputs.Teff_ratio_to_init = struct(...
    'type', 'calculated', ...
    'name', 'Teff_ratio_to_init', ...
    'units', 'dimensionless', ...
    'description', 'Ratio of CD8+ T effector cells at end to initial count', ...
    'timepoint', 'final');

config.outputs.Th_ratio_to_init = struct(...
    'type', 'calculated', ...
    'name', 'Th_ratio_to_init', ...
    'units', 'dimensionless', ...
    'description', 'Ratio of CD4+ T helper cells at end to initial count', ...
    'timepoint', 'final');

%% Cell Densities
config.outputs.CD8_density_final = struct(...
    'type', 'calculated', ...
    'name', 'CD8_density', ...
    'units', 'cell/milliliter', ...
    'description', 'CD8+ T cell density in tumor at end of treatment', ...
    'timepoint', 'final');

config.outputs.CD4_density_final = struct(...
    'type', 'calculated', ...
    'name', 'CD4_density', ...
    'units', 'cell/milliliter', ...
    'description', 'CD4+ T cell density in tumor at end of treatment', ...
    'timepoint', 'final');

%% Tumor Volume
config.outputs.tumor_volume_final = struct(...
    'type', 'compartment', ...
    'name', 'V_T', ...
    'units', 'milliliter', ...
    'description', 'Tumor volume at end of treatment', ...
    'timepoint', 'final');

%% Cell Counts
config.outputs.Teff_tumor_final = struct(...
    'type', 'species', ...
    'name', 'Teff', ...
    'units', 'cell', ...
    'description', 'CD8+ T effector cells in tumor at end of treatment', ...
    'timepoint', 'final', ...
    'compartment', 'V_T');

end
