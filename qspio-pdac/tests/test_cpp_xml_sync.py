"""Guard against drift between the live priors CSV, the C++ XML template,
and any stage-2 snapshot priors.

Delegates to `qsp_codegen.sync_checks.check_priors_csv_names_in_param_xml`
for the priors↔XML consistency check; adds PDAC-specific extras (species
units coverage, stage-2 snapshot allowlist) that aren't part of the
generic harness.

The regeneration flow (Makefile `refresh-cpp`) rewrites
`resources/cpp/param_all.xml` from `PDAC_model.sbml`. Any prior name that
is no longer in the model silently disappears from the XML. Downstream
callers that still pass the retired name blow up inside the XML renderer
with `ParamNotFoundError` — caught in real simulations but not by any
fast test. This module closes that gap.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd
import pytest

from qsp_codegen.sync_checks import check_priors_csv_names_in_param_xml

REPO_ROOT = Path(__file__).resolve().parent.parent
LIVE_PRIORS = REPO_ROOT / "parameters/pdac_priors.csv"
CPP_XML = REPO_ROOT / "resources/cpp/param_all.xml"
# Auto-generated by `make model-structure` (qsp-export-model). Source of truth
# for what the live MATLAB model declares; replaces the older
# hand-maintainable species_units.json.
MODEL_STRUCTURE = REPO_ROOT / "model_structure.json"
STAGE2_SNAPSHOT = REPO_ROOT / "figures/sbi_stage2_current/delta_analysis/input/pdac_priors.csv"

# Params removed from the model but still referenced by frozen stage-2
# snapshots. Add a name here when a retirement lands so the snapshot-vs-XML
# check keeps passing for already-promoted PPC runs; drop it once the
# snapshot is re-promoted against a post-retirement training.
RETIRED_ALLOWLIST: set[str] = {
    "IFNg_50",  # replaced by k_IFNg_response in the averaged-polarization refresh
}


def test_live_priors_covered_by_cpp_xml():
    """Every name in parameters/pdac_priors.csv must render into the C++ XML."""
    ok, msg = check_priors_csv_names_in_param_xml(
        priors_csv=LIVE_PRIORS,
        param_xml=CPP_XML,
    )
    assert ok, msg


def test_live_priors_known_to_model_structure():
    """Every prior name must be a parameter in the auto-generated model structure.

    ``model_structure.json`` is emitted by ``qsp-export-model`` from the live
    MATLAB model. A prior that isn't in the structure's parameter list is
    either a stale row (deleted from the model but still in the CSV) or
    the structure hasn't been regenerated since the model last changed —
    both surface as silent simulator errors downstream.
    """
    live = set(pd.read_csv(LIVE_PRIORS)["name"])
    struct = json.loads(MODEL_STRUCTURE.read_text())
    model_param_names = {p["name"] for p in struct["parameters"]}
    missing = sorted(live - model_param_names)
    assert not missing, (
        f"{len(missing)} prior(s) missing from model_structure.json "
        f"parameters: {missing[:10]}. Run `make model-structure` after "
        f"editing the MATLAB model."
    )


@pytest.mark.skipif(
    not STAGE2_SNAPSHOT.exists(),
    reason="No promoted stage-2 snapshot to validate.",
)
def test_stage2_snapshot_priors_are_xml_known_or_retired():
    """Snapshot priors must either be in the current XML or explicitly retired.

    Snapshot drift is expected (the snapshot is frozen at NPE-training
    time) but each name that has fallen out of the model must show up in
    RETIRED_ALLOWLIST. Otherwise promotion shipped an inconsistent
    artifact and PPC runs will fail against the current binary.

    The generic `check_priors_csv_names_in_param_xml` has no concept of
    an allowlist, so we do the diff inline here — same XML-scan heuristic
    (regex over leaf tags) as the generic helper.
    """
    snap = set(pd.read_csv(STAGE2_SNAPSHOT)["name"])
    xml_names = set(re.findall(r"<([A-Za-z_][\w]*)>", CPP_XML.read_text()))
    orphans = sorted((snap - xml_names) - RETIRED_ALLOWLIST)
    assert not orphans, (
        f"{len(orphans)} snapshot prior(s) missing from XML and not on the "
        f"retirement allowlist: {orphans[:10]}. Either add them to "
        f"RETIRED_ALLOWLIST in tests/test_cpp_xml_sync.py or re-promote "
        f"the stage-2 run against a post-retirement training."
    )
