"""Pydantic schema for prediction-only observable targets.

A ``PredictionTarget`` is a simulator-computed observable used for posterior
predictive / OBED analysis. It shares the computational shape of a
``CalibrationTarget`` (same ``observable.code`` protocol that the qsp-hpc-tools
loader wraps into ``compute_test_statistic``) but carries no empirical data,
provenance, or primary_data_source — the target is a prediction, not a
measurement.

Typical home: ``calibration_targets/predictions/*.yaml``. Generated by
``scripts/generate_prediction_yamls.py`` from pure-Python functions in
``scripts/clinical_endpoints.py``.
"""

from __future__ import annotations

import re
from typing import Literal

from pydantic import BaseModel, Field, field_validator


class Constant(BaseModel):
    """A Pint-unitful constant injected into ``compute_observable``."""

    name: str = Field(min_length=1)
    value: float
    units: str = Field(min_length=1)


class Observable(BaseModel):
    """The computed-observable half of a prediction target."""

    code: str = Field(
        min_length=1,
        description="Python source defining compute_observable(time, species_dict, constants, ureg).",
    )
    units: str = Field(min_length=1, description="Pint-parseable units for the returned quantity.")
    species: list[str] = Field(
        default_factory=list,
        description="Species qualified names (e.g. 'V_T.C1') required from the simulator state.",
    )
    constants: list[Constant] = Field(default_factory=list)

    @field_validator("code")
    @classmethod
    def _must_define_compute_observable(cls, v: str) -> str:
        if not re.search(r"\bdef\s+compute_observable\s*\(", v):
            raise ValueError("observable.code must define `def compute_observable(...)`.")
        try:
            compile(v, "<observable.code>", "exec")
        except SyntaxError as exc:
            raise ValueError(f"observable.code has a syntax error: {exc}") from exc
        return v


class PredictionTarget(BaseModel):
    """A simulator-computed observable for OBED / posterior-predictive use.

    Mirrors the ``CalibrationTarget`` observable-computation protocol (the
    qsp-hpc-tools ``_generate_wrapper_code`` wrapper reads the same fields)
    minus ``empirical_data`` / ``primary_data_source`` and the associated
    extraction provenance. Values come out of the simulator alongside
    calibration-target observables and feed the audit's OBED section.
    """

    prediction_target_id: str = Field(
        min_length=1,
        description="Unique id, snake_case (e.g. 'os_at_12mo').",
    )
    description: str = Field(
        min_length=1,
        description="What this prediction measures and the thresholds it uses.",
    )
    observable: Observable
    scenario: str = Field(
        min_length=1,
        description="Scenario name this prediction is defined for (e.g. 'clinical_progression_longterm').",
    )
    index_values: list[float] | None = None
    index_unit: str | None = None
    index_type: Literal["time", "condition"] | None = None
    rationale: str = Field(
        min_length=1,
        description="Why this prediction matters for OBED / clinical interpretation.",
    )
    tags: list[str] = Field(default_factory=list)

    @field_validator("prediction_target_id")
    @classmethod
    def _id_is_snake_case(cls, v: str) -> str:
        if not re.fullmatch(r"[a-z][a-z0-9_]*", v):
            raise ValueError("prediction_target_id must be snake_case (lowercase, digits, underscores).")
        return v

    @field_validator("index_values")
    @classmethod
    def _index_values_non_empty(cls, v: list[float] | None) -> list[float] | None:
        if v is not None and len(v) == 0:
            raise ValueError("index_values, when provided, must be non-empty.")
        return v
